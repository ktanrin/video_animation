import { resolve } from 'node:path'
import { mkdirSync } from 'node:fs'
process.env.PLAYWRIGHT_BROWSERS_PATH=resolve('.cache/ms-playwright')
const { chromium }=await import('playwright')
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1600,height:1060},deviceScaleFactor:1})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle'})
await page.getByRole('heading',{name:'Ground movement',exact:true}).waitFor()
await page.locator('image').evaluateAll(async images=>{await Promise.all(images.map(el=>new Promise((ok,no)=>{const img=new Image();img.onload=ok;img.onerror=no;img.src=el.getAttribute('href')})))})
mkdirSync('qa',{recursive:true})
await page.screenshot({path:'qa/studio.png',fullPage:true})
await page.getByRole('button',{name:'Chart',exact:true}).click()
await page.screenshot({path:'qa/chart.png',fullPage:true})
await page.getByRole('button',{name:'Presentation',exact:true}).click()
await page.getByRole('button',{name:'Play',exact:true}).click()
await page.waitForFunction(()=>Number(document.querySelector('[aria-label="Video frame"]').value)>70)
await page.getByRole('button',{name:'Pause',exact:true}).click()
await page.getByRole('button',{name:'Hold',exact:true}).click()
const held=await page.locator('[data-aircraft]').getAttribute('data-x')
if(Number(held)!==510)throw new Error('Timeline did not seek to holding position')
await page.getByLabel('Demo aircraft',{exact:true}).uncheck()
if(await page.locator('[data-aircraft]').count())throw new Error('Aircraft toggle failed')
await page.getByLabel('Demo aircraft',{exact:true}).check()
await page.getByRole('button',{name:'Zoom in',exact:true}).click()
await page.getByRole('button',{name:'125%',exact:true}).click()
await page.getByRole('button',{name:'Export video',exact:false}).click()
if(!await page.getByRole('dialog').isVisible())throw new Error('Export instructions missing')
await page.getByRole('button',{name:'Got it'}).click()
await page.getByRole('button',{name:'Restart',exact:true}).click()
await page.setViewportSize({width:390,height:844})
await page.screenshot({path:'qa/mobile.png',fullPage:true})
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
if(overflow)throw new Error('Mobile horizontal overflow')
await browser.close()
if(errors.length)throw new Error(errors.join('\n'))
console.log('Preview passed: map images, playback, seek, layers, zoom, export dialog, mobile layout; no runtime errors.')
